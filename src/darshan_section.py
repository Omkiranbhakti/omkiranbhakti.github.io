            f'<img src="img/live/sm/{live_slug}.webp" alt="{e(name)}" width="300" height="300" loading="lazy">'
            f'<button class="ld-start" type="button"><span>▶ {e(name)} — दर्शन शुरू करें</span></button></div>'
