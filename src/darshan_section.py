def _dg_table(head, rows):
    th = "".join(f"<th>{e(h)}</th>" for h in head)
    tr = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f'<div class="tbl"><table class="ptable"><thead><tr>{th}</tr></thead><tbody>{tr}</tbody></table></div>'

def _dg_list(items):
    return '<ul class="dg-list">' + "".join(f"<li>{x}</li>" for x in items) + "</ul>"

def _ext(url, label=None):
    return f'<a href="{url}" target="_blank" rel="noopener">{label or url.split("//",1)[-1].rstrip("/")}</a>'

def _dg_player(live_slug, name):
    d = _LIVE_BY.get(live_slug)
